package payment

import (
	"context"
	"fmt"
)

// AnonymizeUser removes contact PII from transactional payment records and
// queued/sent email bodies. Financial amounts, provider references, and
// pseudonymous IDs remain intact for accounting, refund, and audit.
func (s *IntentStore) AnonymizeUser(ctx context.Context, userID, oldEmail, tombstone string) (int64, error) {
	if userID == "" || tombstone == "" {
		return 0, fmt.Errorf("payment: anonymize requires user and tombstone")
	}
	res, err := s.db.ExecContext(ctx, `
UPDATE payment_intents SET email=?
WHERE user_id=? OR (? != '' AND email=?)`, tombstone, userID, oldEmail, oldEmail)
	if err != nil {
		return 0, fmt.Errorf("payment: anonymize intents: %w", err)
	}
	return res.RowsAffected()
}

// AnonymizeUserNotifications redacts notification bodies generated by this
// system. It intentionally does not alter provider-side receipts, which must be
// handled through the provider's own data-subject process.
func (s *NotificationStore) AnonymizeUser(ctx context.Context, userID, oldEmail, tombstone string) (int64, error) {
	if userID == "" || tombstone == "" {
		return 0, fmt.Errorf("payment: anonymize notifications requires user and tombstone")
	}
	res, err := s.db.ExecContext(ctx, `
UPDATE payment_notifications AS n
SET to_email=?,
    subject='erased',
    body=''
FROM payment_intents AS pi
WHERE (pi.user_id=? OR (? != '' AND pi.email=?))
  AND n.payment_intent_id=pi.id`, tombstone, userID, oldEmail, oldEmail)
	if err != nil {
		return 0, fmt.Errorf("payment: anonymize notifications: %w", err)
	}
	return res.RowsAffected()
}
