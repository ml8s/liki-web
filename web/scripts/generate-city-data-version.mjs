#!/usr/bin/env node
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const dataPath = path.join(root, 'web', 'public', 'data', 'cities_data.json')
const outPath = path.join(root, 'web', 'shared', 'generated', 'cityData.ts')
const hash = crypto.createHash('sha256').update(fs.readFileSync(dataPath)).digest('hex').slice(0, 16)
const content = `// Generated by web/scripts/generate-city-data-version.mjs. Do not edit.
export const CITY_DATA_VERSION = '${hash}'
export const CITY_DATA_URL = '/data/cities_data.json?v=${hash}'
`

if (process.argv.includes('--check')) {
  if (!fs.existsSync(outPath) || fs.readFileSync(outPath, 'utf8') !== content) {
    console.error('✗ city data version is stale; run node web/scripts/generate-city-data-version.mjs')
    process.exit(1)
  }
  console.log(`✓ city data version ${hash}`)
  process.exit(0)
}

fs.mkdirSync(path.dirname(outPath), { recursive: true })
fs.writeFileSync(outPath, content)
console.log(`✓ city data version ${hash}`)
