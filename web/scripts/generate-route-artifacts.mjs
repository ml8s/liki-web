#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const check = process.argv.includes('--check');
const readJson = value => JSON.parse(fs.readFileSync(value, 'utf8'));
const intents = readJson(path.join(root, 'shared/config/intents.json'));
const marketing = readJson(path.join(root, 'routes/marketing.contract.json'));
const generatedDir = path.join(root, 'routes/generated');

const artifacts = new Map();
artifacts.set(path.resolve(root, '../internal/http/routes.generated.json'), `${JSON.stringify({
  version: 1,
  locales: marketing.locales,
  canonicalSlugs: intents.intents.map(item => item.marketingSlug),
  bareRedirects: marketing.bareRedirects,
  retired: marketing.retired,
}, null, 2)}\n`);
artifacts.set(path.join(generatedDir, 'intents.generated.ts'), `// generated by web/scripts/generate-route-artifacts.mjs; do not edit\nexport type IntentRouteId = ${intents.intents.map(item => `'${item.id}'`).join(' | ')}\n\nexport interface IntentRoute {\n  id: IntentRouteId\n  marketingSlug: string\n  serviceParam: string\n  appPath?: string\n}\n\nexport const intentRoutes = ${JSON.stringify(intents.intents, null, 2)} as const\n`);

const redirects = marketing.bareRedirects.map(item =>
  `\tredir ${item.path} /{marketing_lang}/${item.slug}/ ${item.status}`).join('\n');
const caddyBlock = `\t# generated:bare-redirects begin\n${redirects}\n\t# generated:bare-redirects end\n`;
const caddyFiles = [
  path.resolve(root, '../dev/Caddyfile.local'),
  process.env.LIKI_DEPLOY_CADDYFILE ?? path.resolve(root, '../../liki-deploy/caddy/Caddyfile'),
];

for (const [destination, content] of artifacts) {
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  if (check) {
    const actual = fs.existsSync(destination) ? fs.readFileSync(destination, 'utf8') : '';
    if (actual !== content) {
      console.error(`✗ generated route artifact is stale: ${path.relative(process.cwd(), destination)}`);
      process.exitCode = 1;
    }
    continue;
  }
  fs.writeFileSync(destination, content);
}

for (const destination of caddyFiles) {
  if (!fs.existsSync(destination)) {
    if (check) continue;
    throw new Error(`Caddyfile not found: ${destination}`);
  }
  const source = fs.readFileSync(destination, 'utf8');
  const begin = '\t# generated:bare-redirects begin';
  const end = '\t# generated:bare-redirects end';
  const startIndex = source.indexOf(begin);
  const endIndex = source.indexOf(end);
  if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) {
    console.error(`✗ generated route markers missing in ${destination}`);
    process.exitCode = 1;
    continue;
  }
  const updated = source.slice(0, startIndex) + caddyBlock.trimEnd() + source.slice(endIndex + end.length);
  if (check) {
    if (updated !== source) {
      console.error(`✗ generated Caddy redirects are stale: ${destination}`);
      process.exitCode = 1;
    }
    continue;
  }
  try {
    fs.writeFileSync(destination, updated);
  } catch (error) {
    if (error.code !== 'EROFS') throw error;
    console.warn(`⚠ read-only deployment repo; skipped write: ${destination}`);
  }
}

if (process.exitCode === 1) process.exit(1);
console.log(check ? '✓ generated route artifacts are up to date' : '✓ generated route artifacts');
